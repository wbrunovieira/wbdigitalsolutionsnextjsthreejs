// Rich, NON-CONFIDENTIAL detail content for individual project pages, keyed by
// slug then language. Capability-level only (no business rules, data or secrets).
//
// Reading order on the page answers, in this order, what a business owner asks:
//   problem  -> what problem did it solve
//   features -> what can it do
//   result   -> did it turn out well
//   stats    -> the few numbers a buyer can read
//   highlights -> engineering depth, explicitly addressed to technical visitors
//
// Every number and capability here was verified against the project's source
// code. Nothing is stated that the code does not support.

export interface DetailFeature {
  icon: string;
  title: string;
  description: string;
}

export interface DetailStat {
  value: string;
  label: string;
}

